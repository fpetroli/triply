def _e(text: Any) -> str:
    return html.escape(str(text), quote=True)


def _a(url: str, text: str) -> str:
    return f'<a href="{_e(url)}" target="_blank" rel="noopener">{_e(text)}</a>'


def _links_html(booking: Dict[str, Any]) -> str:
    links = booking.get("links") or ([{"label": booking["search_url"], "url": booking["search_url"]}] if booking.get("search_url") else [])
    return " · ".join(_a(link["url"], link["label"]) for link in links)


def _check_html(check: Dict[str, Any], L: Dict[str, Any]) -> str:
    status = check.get("status")
    if status == "failed":
        return f'<div class="bad">{_e(L["problem"])}: {_e(check.get("notes", ""))}</div>'
    if status == "warning":
        return f'<div class="warn">{_e(L["to_review"])}: {_e(check.get("notes", ""))}</div>'
    return ""


