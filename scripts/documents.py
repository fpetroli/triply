def labels_file(triply_dir: Path, language: str) -> Path:
    return triply_dir / f"labels-{language.split('-')[0]}.json"


def load_labels(language: str, triply_dir: Path) -> Tuple[Dict[str, Any], List[str]]:
    """The labels of the language, and the keys still missing (shown in English meanwhile)."""
    code = language.split("-")[0]
    labels = dict(LABELS["en"])
    if code in LABELS:
        labels.update(LABELS[code])
        return labels, []
    custom: Dict[str, Any] = {}
    try:
        loaded = json.loads(labels_file(triply_dir, language).read_text(encoding="utf-8"))
        if isinstance(loaded, dict):
            custom = {k: v for k, v in loaded.items() if k in LABELS["en"] and isinstance(v, type(LABELS["en"][k]))}
    except (OSError, ValueError):
        pass
    labels.update(custom)
    return labels, sorted(k for k in LABELS["en"] if k not in custom)


# ----------------------------------------------------------------- helpers


def _date(text: str) -> datetime.date:
    return datetime.date.fromisoformat(text)


def fmt_date(text: str, L: Dict[str, Any]) -> str:
    day = _date(text)
    return L["date_format"].format(
        weekday=L["weekdays"][day.weekday()], day=day.day, month=L["months"][day.month - 1], year=day.year
    )


def fmt_duration(minutes: int, L: Dict[str, Any]) -> str:
    hours, rest = divmod(minutes, 60)
    if not hours:
        return f"{rest} {L['minutes']}"
    return f"{hours} {L['hours']}" + (f" {rest:02d}" if rest else "")


def _slug(text: str) -> str:
    ascii_text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", ascii_text.lower()).strip("-") or "item"


def _osm_link(place: Dict[str, Any]) -> str:
    lat, lon = place["lat"], place["lon"]
    return f"https://www.openstreetmap.org/?mlat={lat}&mlon={lon}#map=17/{lat}/{lon}"


def _stay_of(data: Dict[str, Any], stay_id: Optional[str]) -> Optional[Dict[str, Any]]:
    return next((s for s in data.get("stays", []) if s["id"] == stay_id), None)


def _weather_for(data: Dict[str, Any], place_id: str, date: str) -> Optional[Dict[str, Any]]:
    found = [w for w in data.get("weather", []) if w["place"] == place_id and w["start"] <= date <= w["end"]]
    found.sort(key=lambda w: (w["kind"] != "forecast", w["start"]))
    return found[0] if found else None


def _weather_line(entry: Dict[str, Any], L: Dict[str, Any]) -> str:
    parts = []
    if "temp_min_c" in entry and "temp_max_c" in entry:
        parts.append(f"{round(entry['temp_min_c'])}–{round(entry['temp_max_c'])} °C")
    if entry["kind"] == "climate" and "rain_days" in entry:
        parts.append(f"{entry['rain_days']:g} {L['rain_days']}")
    if entry["kind"] == "forecast" and "rain_probability_pct" in entry:
        parts.append(f"{L['rain_chance']} {round(entry['rain_probability_pct'])}%")
    parts.append(L["weather_" + entry["kind"]])
    text = ", ".join(parts)
    return f"{entry['summary']} ({text})" if entry.get("summary") else text


def _moves_on(data: Dict[str, Any], date: str) -> List[Dict[str, Any]]:
    return [m for m in data.get("transports", []) if m["date"] == date]


def _move_title(move: Dict[str, Any], data: Dict[str, Any], L: Dict[str, Any]) -> str:
    places = data["places"]
    text = f"{L['transport_' + move['mode']]} {places[move['from']]['name']} → {places[move['to']]['name']}"
    times = "–".join(t for t in (move.get("depart_time"), move.get("arrive_time")) if t)
    return f"{text} {times}".strip()


def _stay_title(stay: Dict[str, Any], data: Dict[str, Any]) -> str:
    town = data["places"][stay["place"]]["name"]
    return f"{stay['name']} ({town})" if stay.get("name") else town


def _booking_text(booking: Dict[str, Any], L: Dict[str, Any]) -> str:
    text = L["booking_" + booking["status"]]
    if booking.get("reference"):
        text += f", {L['reference']} {booking['reference']}"
    if booking.get("cost"):
        text += f", {booking['cost']['amount']:g} {booking['cost']['currency']}"
    return text


def _open_deadlines(data: Dict[str, Any]) -> List[Dict[str, Any]]:
    return sorted((d for d in data.get("deadlines", []) if not d["done"]), key=lambda d: (d["due"], d["title"]))


def _sources(data: Any) -> List[Dict[str, Any]]:
    """Every source with a link in the trip file, once."""
    found: Dict[str, Dict[str, Any]] = {}

    def walk(value: Any) -> None:
        if isinstance(value, dict):
            if "provider" in value and "checked_at" in value and value.get("url"):
                found.setdefault(value["url"], value)
            for sub in value.values():
                walk(sub)
        elif isinstance(value, list):
            for sub in value:
                walk(sub)

    walk(data)
    return sorted(found.values(), key=lambda s: (s.get("title") or s["url"]).lower())


def _trip_dates(data: Dict[str, Any], L: Dict[str, Any]) -> str:
    dates = data["constraints"]["dates"]
    if dates.get("start") and dates.get("end"):
        return f"{fmt_date(dates['start'], L)} – {fmt_date(dates['end'], L)}"
    if dates.get("window_start") and dates.get("window_end"):
        return f"{fmt_date(dates['window_start'], L)} – {fmt_date(dates['window_end'], L)}"
    return ""


def _map_data(data: Dict[str, Any]) -> Dict[str, Any]:
    places = data["places"]

    def point(place_id: str, label: str) -> Dict[str, Any]:
        place = places[place_id]
        return {"lat": place["lat"], "lon": place["lon"], "name": place["name"], "label": label}

    bases: List[Dict[str, Any]] = []
    for n, stay in enumerate(sorted(data.get("stays", []), key=lambda s: s["check_in"]), 1):
        bases.append(point(stay["place"], str(n)))
    route = []
    for move in sorted(data.get("transports", []), key=lambda m: m["date"]):
        for place_id in (move["from"], move["to"]):
            p = places[place_id]
            if not route or route[-1] != [p["lon"], p["lat"]]:
                route.append([p["lon"], p["lat"]])
    days = {}
    for d, day in enumerate(data["days"]):
        stops = [point(item["place"], str(i + 1)) for i, item in enumerate(i for i in day["items"] if i["role"] != "backup")]
        if stops:
            days[str(d)] = stops
    return {"bases": bases, "route": route, "days": days}


