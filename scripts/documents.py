"""The documents of a trip for the user, generated from the trip file.

Standard library only. The same trip file always gives the same documents:

- the itinerary as a web page with maps (``Itinerary.html``) and as Markdown
  (``Itinerary.md``);
- a calendar (``Calendar.ics``) with the deadlines, each with two reminders,
  and the trip itself: stays and moves between bases;
- the packing list to tick off (``Packing.md``): before it is written again,
  the ticks the user changed in the file are read back into the trip file.

File names and fixed texts are in the trip's language: English and Italian
are built in; for another language Claude writes the translation once in
``.triply/labels-<language>.json`` (``missing_labels`` lists what is needed).

The maps use OpenFreeMap (vector tiles from OpenStreetMap data, no key) with
MapLibre GL JS: a key of Mapbox or Google never goes into a file that may be
shared. Without internet the page works, without maps.

A file that exists and was not made by triply is never overwritten.
"""

