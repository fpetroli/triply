def _md(text: Any) -> str:
    """Text safe inside a Markdown line: no line breaks, no stray markup at the start."""
    return re.sub(r"\s+", " ", str(text)).strip().replace("|", "\\|")


def _md_links(booking: Dict[str, Any]) -> str:
    links = booking.get("links") or ([{"label": "↗", "url": booking["search_url"]}] if booking.get("search_url") else [])
    return " · ".join(f"[{_md(link['label'])}]({link['url']})" for link in links)


