    result: Dict[str, Any] = {"written": [], "skipped": [], "ticks_read": 0}
    packing_file = names["packing"]
    if packing_file.is_file() and _ours(packing_file):
        result["ticks_read"] = read_ticks(packing_file.read_text(encoding="utf-8", errors="replace"), data)
    contents = {
        "itinerary_html": render_html(data, L),
        "itinerary_md": render_markdown(data, L),
        "calendar": render_calendar(data, L),
    }
    if data.get("packing"):
        contents["packing"] = render_packing(data, L)
    for kind, text in contents.items():
        path = names[kind]
        if path.exists() and not _ours(path):
            result["skipped"].append(str(path))
            continue
        newline = "" if kind == "calendar" else None
        with open(path, "w", encoding="utf-8", newline=newline) as handle:
            handle.write(text)
        result["written"].append(str(path))
    if missing:
        result["missing_labels"] = {"file": str(labels_file(triply_dir, data["trip"]["language"])), "keys": missing, "english": {k: LABELS["en"][k] for k in missing}}
    return result
