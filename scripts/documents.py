_TICK = re.compile(r"^\s*[-*+] \[(?P<box>[ xX])\]\s+(?P<text>.*?)\s*(?:<!-- triply:(?P<key>[a-z0-9-]+):(?P<was>[01]) -->)?\s*$")
CATEGORIES = ("documents", "clothing", "health", "electronics", "toiletries", "gear", "other")


def packing_keys(packing: List[Dict[str, Any]]) -> List[str]:
    keys: List[str] = []
    for item in packing:
        base = _slug(item["item"] + (f"-{item['traveller']}" if item.get("traveller") else ""))
        key, n = base, 2
        while key in keys:
            key, n = f"{base}-{n}", n + 1
        keys.append(key)
    return keys


def read_ticks(text: str, data: Dict[str, Any]) -> int:
    """Bring into the trip file what the user changed in the packing list file. Returns the number of changes.

    A line made by triply carries its key and the state it was written with:
    when the box differs from that state, the user ticked or unticked it in
    the file, and the file wins. A checkbox line without a key is an item the
    user added: it joins the list.
    """
    packing = data.setdefault("packing", [])
    index = dict(zip(packing_keys(packing), packing))
    changes = 0
    for line in text.splitlines():
        match = _TICK.match(line)
        if not match:
            continue
        ticked = match["box"] in "xX"
        if match["key"]:
            item = index.get(match["key"])
            if item is not None and ticked != (match["was"] == "1"):
                item["packed"] = ticked
                changes += 1
        elif match["text"]:
            packing.append({"item": match["text"], "category": "other", "packed": ticked})
            changes += 1
    return changes


def render_packing(data: Dict[str, Any], L: Dict[str, Any]) -> str:
    packing = data.get("packing", [])
    names = {t["id"]: t["label"] for t in data["travellers"]}
    keys = packing_keys(packing)
    out = [f"<!-- {MARK} -->", f"# {_md(L['packing'])} — {_md(data['trip']['title'])}", "", f"*{_md(L['generated_packing'].format(date=fmt_date(data['trip']['updated'], L)))}*", ""]
    packed = sum(1 for p in packing if p["packed"])
    out += [_md(L["packed_count"].format(packed=packed, total=len(packing))), ""]
    for category in CATEGORIES:
        items = [(k, p) for k, p in zip(keys, packing) if p["category"] == category]
        if not items:
            continue
        out += [f"## {_md(L['cat_' + category])}", ""]
        for key, item in items:
            text = _md(item["item"])
            if item.get("quantity", 1) > 1:
                text += f" ×{item['quantity']}"
            if item.get("traveller"):
                text += f" ({_md(names.get(item['traveller'], item['traveller']))})"
            if item.get("reason"):
                text += f" — {_md(item['reason'])}"
            out.append(f"- [{'x' if item['packed'] else ' '}] {text} <!-- triply:{key}:{1 if item['packed'] else 0} -->")
        out.append("")
    return "\n".join(out)


