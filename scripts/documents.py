def _ics_text(text: str) -> str:
    return str(text).replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\r\n", "\\n").replace("\n", "\\n")


def _fold(line: str) -> List[str]:
    """Lines of at most 75 octets, as RFC 5545 asks."""
    parts, current = [], ""
    for char in line:
        limit = 75 if not parts else 74
        if len((current + char).encode("utf-8")) > limit:
            parts.append(current)
            current = char
        else:
            current += char
    parts.append(current)
    return [parts[0]] + [" " + p for p in parts[1:]]


def _day(text: str) -> str:
    return text.replace("-", "")


def render_calendar(data: Dict[str, Any], L: Dict[str, Any]) -> str:
    trip = data["trip"]
    stamp = _day(trip["updated"]) + "T000000Z"
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//triply//trip calendar//EN", "CALSCALE:GREGORIAN", f"X-WR-CALNAME:{_ics_text(trip['title'])}"]

    def event(uid: str, start: str, end: str, summary: str, description: str = "", url: str = "", alarms: bool = False) -> None:
        lines.extend(["BEGIN:VEVENT", f"UID:{trip['id']}-{uid}@triply", f"DTSTAMP:{stamp}",
                      f"DTSTART;VALUE=DATE:{_day(start)}", f"DTEND;VALUE=DATE:{_day(end)}", f"SUMMARY:{_ics_text(summary)}"])
        if description:
            lines.append(f"DESCRIPTION:{_ics_text(description)}")
        if url:
            lines.append(f"URL:{url}")
        lines.append("TRANSP:TRANSPARENT")
        if alarms:
            # 09:00 a week before and 09:00 the day before (the event starts at 00:00 of its day).
            for trigger in ("-P6DT15H", "-PT15H"):
                lines.extend(["BEGIN:VALARM", "ACTION:DISPLAY", f"TRIGGER:{trigger}", f"DESCRIPTION:{_ics_text(L['reminder'] + ': ' + summary)}", "END:VALARM"])
        lines.append("END:VEVENT")

    def next_day(text: str) -> str:
        return (_date(text) + datetime.timedelta(days=1)).isoformat()

    for deadline in _open_deadlines(data):
        url = deadline.get("search_url", "")
        event(f"deadline-{deadline['id']}", deadline["due"], next_day(deadline["due"]), deadline["title"],
              deadline.get("reason", ""), url, alarms=True)
    for stay in data.get("stays", []):
        booking = stay["booking"]
        links = booking.get("links") or []
        description = "\n".join([_booking_text(booking, L)] + [f"{link['label']}: {link['url']}" for link in links])
        event(f"stay-{stay['id']}", stay["check_in"], stay["check_out"], f"{L['stay']}: {_stay_title(stay, data)}", description)
    for move in data.get("transports", []):
        booking = move["booking"]
        parts = [_booking_text(booking, L)]
        if move.get("notes"):
            parts.append(move["notes"])
        parts += [f"{link['label']}: {link['url']}" for link in booking.get("links") or []]
        event(f"move-{move['id']}", move["date"], next_day(move["date"]), _move_title(move, data, L), "\n".join(parts))
    lines.append("END:VCALENDAR")
    folded = [part for line in lines for part in _fold(line)]
    return "\r\n".join(folded) + "\r\n"


